    def _set_all_layers_check_state(self, check_state):
        """
        Applique un état coché/décoché à toutes les couches affichées.
        """

        self.list_couches.blockSignals(True)

        for index in range(self.list_couches.count()):
            item = self.list_couches.item(index)
            item.setCheckState(check_state)

            layer_id = item.data(QT_USER_ROLE)
            if layer_id:
                self.layer_check_states[layer_id] = check_state

        self.list_couches.blockSignals(False)

        self.update_layers_counter()

    def update_layers_counter(self):
        """
        Met à jour le nombre de couches visibles et sélectionnées dans le plugin.
        """

        total = self.list_couches.count()
        selected = 0

        for index in range(total):
            item = self.list_couches.item(index)

            if item.checkState() == QT_CHECKED:
                selected += 1

        self.lbl_couches_visibles.setText(
            f"Couches visibles : {total} | sélectionnées : {selected}"
        )


    def get_visible_layers(self):
        """
        Retourne les couches visibles du projet QGIS.

        La notion de visibilité utilisée ici correspond aux couches cochées
        dans l'arbre des couches QGIS.

        :return: liste de QgsMapLayer
        """

        project = QgsProject.instance()
        root = project.layerTreeRoot()

        visible_layers = []

        for layer in project.mapLayers().values():
            node = root.findLayer(layer.id())

            if node is None:
                continue

            try:
                is_visible = bool(node.isVisible())
            except AttributeError:
                # Fallback prudent si l'API évolue.
                # Dans QGIS 3, isVisible() est public sur QgsLayerTreeNode.
                is_visible = True

            if is_visible:
                visible_layers.append(layer)

        return visible_layers

    def _layer_label(self, layer):
        """
        Construit un libellé lisible pour une couche.

        :param layer: QgsMapLayer
        :return: texte affiché dans la liste
        """

        layer_type = "Couche"

        if isinstance(layer, QgsVectorLayer):
            layer_type = "Vecteur"
        elif isinstance(layer, QgsRasterLayer):
            provider = ""
            try:
                provider = layer.providerType()
            except Exception:
                provider = ""

            if provider.lower() in ("wms", "wmts"):
                layer_type = "WMS/WMTS"
            else:
                layer_type = "Raster"

        return f"{layer.name()} [{layer_type}]"

    def get_checked_layer_ids(self):
        """
        Retourne les identifiants des couches cochées dans list_couches.

        :return: liste d'identifiants de couches QGIS
        :rtype: list[str]
        """

        layer_ids = []

        for index in range(self.list_couches.count()):
            item = self.list_couches.item(index)

            if item.checkState() == QT_CHECKED:
                layer_id = item.data(QT_USER_ROLE)
                if layer_id:
                    layer_ids.append(layer_id)

        return layer_ids

