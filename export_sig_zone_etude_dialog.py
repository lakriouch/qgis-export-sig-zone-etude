    def ouvrir_selecteur_site_cen(self):
        """
        Ouvre la fenêtre de sélection d'un site CEN quand l'utilisateur clique
        sur le mode 'Site CEN'.
        """

        if not self.radio_site_cen.isChecked():
            return

        dlg = SelecteurSiteCEN(
            pg_service_path=self.pg_service_path,
            pg_service_name="bd CEN (admin)",
            parent=self
        )

        result = exec_dialog(dlg)

        if result != QDIALOG_ACCEPTED:
            self.log("Sélection du site CEN annulée.")

            if self.zone_etude is None:
                self.radio_dessiner.setChecked(True)

                if hasattr(self, "lbl_site_cen_selectionne"):
                    self.lbl_site_cen_selectionne.setText("Site sélectionné : aucun")

                self.lbl_zone_status.setText("Zone : aucune")

            return

        codesitep = dlg.selected_codesitep
        nomsitep = dlg.selected_nomsitep
        communes = dlg.selected_communes

        if not codesitep:
            self.log("Aucun site CEN sélectionné.")
            self.radio_dessiner.setChecked(True)
            return

        zone = charger_zone_bdd(
            codesitep=codesitep,
            nomsitep=nomsitep,
            communes=communes,
            pg_service_path=self.pg_service_path
        )

        if zone is None:
            self.log("Erreur : impossible de charger le site CEN depuis la BDD.")
            self.radio_dessiner.setChecked(True)
            self.lbl_zone_status.setText("Zone : erreur chargement site CEN")
            return

        self.zone_etude = zone
        self.zone_source = "site_cen"

        self.selected_codesitep = codesitep
        self.selected_nomsitep = nomsitep
        self.selected_communes = communes

        if communes:
            texte_site = f"{nomsitep} - {communes} ({codesitep})"
        else:
            texte_site = f"{nomsitep} ({codesitep})"

        if hasattr(self, "lbl_site_cen_selectionne"):
            self.lbl_site_cen_selectionne.setText(
                f"Site sélectionné : {texte_site}"
            )

        self.lbl_zone_status.setText(
            f"Zone : site CEN - {texte_site}"
        )

        self.log(f"Site CEN chargé : {texte_site}")





