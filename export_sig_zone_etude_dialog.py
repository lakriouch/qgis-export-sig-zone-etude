    def refresh_visible_layers(self):
        """
        Actualise la liste des couches visibles dans QGIS.

        Important :
        - les couches visibles dans QGIS sont affichées dans le plugin ;
        - les choix cochés/décochés dans le plugin sont conservés ;
        - une nouvelle couche visible est cochée par défaut.
        """

        self._save_current_layer_check_states()

        self.list_couches.blockSignals(True)
        self.list_couches.clear()

        visible_layers = self.get_visible_layers()

        for layer in visible_layers:
            layer_id = layer.id()

            item = QListWidgetItem(self._layer_label(layer))
            item.setData(QT_USER_ROLE, layer_id)

            # Si l'utilisateur avait déjà coché/décoché cette couche dans le plugin,
            # on restaure son choix.
            if layer_id in self.layer_check_states:
                item.setCheckState(self.layer_check_states[layer_id])
            else:
                # Nouvelle couche visible : cochée par défaut.
                item.setCheckState(QT_CHECKED)

            self.list_couches.addItem(item)

        self.list_couches.blockSignals(False)

        self.update_layers_counter()
        self.log(f"{len(visible_layers)} couche(s) visible(s) détectée(s).")

    def _save_current_layer_check_states(self):
        """
        Sauvegarde l'état actuel des cases de la liste des couches.

        Cela permet de conserver les choix de l'utilisateur quand il clique
        sur Actualiser.
        """

        for index in range(self.list_couches.count()):
            item = self.list_couches.item(index)
            layer_id = item.data(QT_USER_ROLE)

            if layer_id:
                self.layer_check_states[layer_id] = item.checkState()

