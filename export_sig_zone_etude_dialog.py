    def get_output_suffix(self):
        """
        Retourne le suffixe nettoyé pour le nom du fichier.
        """

        suffixe = self.line_suffixe.text().strip()

        if not suffixe:
            suffixe = "export"

        suffixe = suffixe.replace(" ", "_")

        caracteres_interdits = ['\\', '/', ':', '*', '?', '"', '<', '>', '|']

        for caractere in caracteres_interdits:
            suffixe = suffixe.replace(caractere, "_")

        return suffixe


    def get_output_filename(self):
        """
        Retourne le nom du fichier GeoPackage.
        """

        date_inv = datetime.now().strftime("%Y%m%d")
        suffixe = self.get_output_suffix()

        return f"{date_inv}_SIG_{suffixe}.gpkg"


    def get_output_path(self):
        """
        Retourne le chemin complet du GeoPackage de sortie.
        """

        dossier = self.line_dossier_sortie.text().strip()

        if not dossier:
            return ""

        nom_fichier = self.get_output_filename()

        return os.path.join(dossier, nom_fichier)


    def update_output_filename(self):
        """
        Met à jour le label qui affiche le nom du fichier de sortie.
        """

        nom_fichier = self.get_output_filename()
        self.lbl_fichier_sortie.setText(nom_fichier)


